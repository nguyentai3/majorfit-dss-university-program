function buildMatchingExplanationPrompt({
    studentProfile,
    student,
    program,
    scoring,
    deterministicExplanation,
    competingPrograms,
    locale,
}) {
    const userPrompt = JSON.stringify(
        {
            locale: locale || 'en',
            student: {
                name: student?.name || null,
                gradeLevel: student?.gradeLevel || null,
                semester: student?.semester || null,
                totalAttempts: student?.totalAttempts || 0,
            },
            studentProfile: {
                latestHollandCode: studentProfile?.latestHollandCode || null,
                stableScores: studentProfile?.stableScores || {},
                growth: studentProfile?.growth || [],
                confidenceScore: studentProfile?.confidenceScore || 0,
            },
            program: {
                name: program?.name,
                university: program?.university?.name || null,
                focusArea: program?.focusArea || null,
                riasecScores: program?.latestProfile?.riasecScores || {},
                extractedSkills: program?.latestProfile?.extractedSkills || [],
            },
            scoring,
            deterministicExplanation,
            competingPrograms: Array.isArray(competingPrograms) ? competingPrograms : [],
        },
        null,
        2,
    );

    return {
        promptVersion: MATCHING_EXPLANATION_PROMPT_VERSION,
        responseVersion: MATCHING_EXPLANATION_RESPONSE_VERSION,
        systemPrompt: EXPLANATION_SYSTEM_PROMPT,
        userPrompt,
    };
}

module.exports = {
    MATCHING_EXPLANATION_PROMPT_VERSION,
    MATCHING_EXPLANATION_RESPONSE_VERSION,
    buildMatchingExplanationPrompt,
};
